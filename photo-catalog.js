const photoAliases = new Map();
for (const [path, photo] of Object.entries(photoCatalog)) {
  for (const alias of photo.aliases || []) photoAliases.set(alias, path);
}

function findPhoto(path) {
  const clean = (path || '').replace(/^\.\//, '').split(/[?#]/)[0];
  return photoCatalog[photoAliases.get(clean) || clean];
}
